"""صياغة المشتريات بالفصحى، و«أخرى» بدل «غير مدرج» في النموذجين.

المستند يطلب فصحى مبسطة في السؤال والاختيار، ويضرب «المرحلة دي بتحصل عندكم؟»
مثالًا لما يُصحَّح. وكان 239 سؤالًا من 400 في المشتريات بالمحكية، والنموذج المالي
خاليًا منها — وهو ما يفسّر أن كل أمثلة المستند في قسم اللغة من المشتريات.

أُعيدت صياغة 111 نصًّا مميزًا، والمعنى كما هو؛ ما تغيّر هو السجل اللغوي.
و«غير مدرج» صارت «أخرى» في 370 خيارًا — والنوع not_listed باقٍ، فهو ما يقرؤه
المحرك. وأُضيفت «لا توجد سياسة ولا ممارسة محددة» إلى حالات السياسة، إذ لم يكن
فيها ما يصف الكيان الذي لا سياسة له ولا ممارسة.
"""
import logging

_logger = logging.getLogger(__name__)


def migrate(cr, version):
    from odoo import SUPERUSER_ID, api
    env = api.Environment(cr, SUPERUSER_ID, {})
    env["azm.stage"]._load_catalogue()
    env["azm.fin.module"]._load_catalogue()
    if "azm.artifact" in env:
        env["azm.artifact"]._register_all()
    _logger.info("أُعيد تحميل الكتالوجين بعد إعادة الصياغة")
